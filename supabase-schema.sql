CREATE OR REPLACE FUNCTION public.editar_lote_transferencia(
  p_lote_id BIGINT, p_establecimiento UUID, p_cantidad INTEGER,
  p_valor_unitario NUMERIC, p_fuente TEXT, p_referencia TEXT, p_fecha_valorizacion DATE
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE v_lote public.lotes_medicamentos%ROWTYPE;
BEGIN
  IF NOT public.vlogp_miembro_activo(p_establecimiento, ARRAY['director_tecnico', 'encargado_inventario']) THEN
