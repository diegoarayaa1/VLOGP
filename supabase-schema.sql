create table if not exists public.lotes_medicamentos (
  id bigint generated by default as identity primary key,
  principio_activo text not null,
  laboratorio text not null,
  registro_isp text not null,
  numero_lote text not null,
  fecha_vencimiento date not null,
  cantidad_cajas integer not null check (cantidad_cajas > 0),
  precio_oferta numeric(12, 2) not null check (precio_oferta > 0),
  comuna text not null,
  vendedor_id uuid not null default auth.uid() references auth.users (id),
  created_at timestamptz not null default now()
);

alter table public.lotes_medicamentos enable row level security;

grant select on public.lotes_medicamentos to anon, authenticated;
grant insert on public.lotes_medicamentos to authenticated;
grant usage, select on sequence public.lotes_medicamentos_id_seq to authenticated;

drop policy if exists "Anyone can read medication lots" on public.lotes_medicamentos;
create policy "Anyone can read medication lots"
  on public.lotes_medicamentos
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Authenticated users can publish their own medication lots" on public.lotes_medicamentos;
create policy "Authenticated users can publish their own medication lots"
  on public.lotes_medicamentos
  for insert
  to authenticated
  with check (auth.uid() = vendedor_id);
