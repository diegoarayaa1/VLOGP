    RAISE EXCEPTION 'Debes pertenecer a un establecimiento habilitado para publicar inventario';
  END IF;
  IF NULLIF(trim(p_principio_activo), '') IS NULL OR NULLIF(trim(p_laboratorio), '') IS NULL
    OR NULLIF(trim(p_registro_isp), '') IS NULL OR NULLIF(trim(p_numero_lote), '') IS NULL
    OR p_fecha_vencimiento IS NULL THEN
    RAISE EXCEPTION 'Completa principio activo, laboratorio, registro ISP, número de lote y vencimiento';
  END IF;
  IF lower(p_principio_activo) ~ '\m(fentanilo?|clonazepam|morfina)\M' THEN
    RAISE EXCEPTION 'Este medicamento de control legal estricto está fuera del alcance de la plataforma';
  END IF;
  IF p_fecha_vencimiento < current_date + 60 THEN
    RAISE EXCEPTION 'El medicamento debe mantener al menos 60 días de vigencia';
  END IF;
  IF p_cantidad IS NULL OR p_cantidad <= 0 OR p_valor_unitario IS NULL OR p_valor_unitario <= 0 THEN
    RAISE EXCEPTION 'La cantidad y la valorización unitaria deben ser mayores que cero';
  END IF;
  IF p_fuente IS NULL OR p_fuente NOT IN ('costo_adquisicion', 'cenabast') OR NULLIF(trim(p_referencia), '') IS NULL OR p_fecha_valorizacion IS NULL THEN
    RAISE EXCEPTION 'Indica fuente, referencia documental y fecha de valorización';
  END IF;
  SELECT email INTO v_email FROM auth.users WHERE id = auth.uid();
  SELECT nombre, comuna INTO v_nombre, v_comuna FROM public.establecimientos WHERE id = p_establecimiento;
  INSERT INTO public.lotes_medicamentos (
    principio_activo, farmacia_origen, marca_presentacion, laboratorio, comuna,
    registro_isp, numero_lote, fecha_vencimiento, cantidad_cajas,
    precio_original, precio_oferta, publicado_por, vendedor_id, estado,
    establecimiento_donante_id, valor_unitario_clp, fuente_valorizacion,
    referencia_valorizacion, fecha_valorizacion
  ) VALUES (
    NULLIF(trim(p_principio_activo), ''), v_nombre, NULLIF(trim(p_marca_presentacion), ''),
    NULLIF(trim(p_laboratorio), ''), v_comuna, NULLIF(trim(p_registro_isp), ''),
    NULLIF(trim(p_numero_lote), ''), p_fecha_vencimiento, p_cantidad,
    NULL, NULL, v_email, auth.uid(), 'disponible', p_establecimiento,
    p_valor_unitario, p_fuente, trim(p_referencia), p_fecha_valorizacion
  )
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.catalogo_transferencias()
RETURNS TABLE (
  id BIGINT, principio_activo TEXT, marca_presentacion TEXT, laboratorio TEXT,
  numero_lote TEXT, fecha_vencimiento DATE, cantidad_disponible INTEGER,
  comuna TEXT, establecimiento_donante_id UUID, establecimiento_donante TEXT,
  valor_unitario_clp NUMERIC, fuente_valorizacion TEXT, registro_isp TEXT
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.establecimiento_usuarios eu
    JOIN public.establecimientos e ON e.id = eu.establecimiento_id
    WHERE eu.usuario_id = auth.uid() AND eu.activo AND e.estado = 'habilitado'
  ) THEN
    RAISE EXCEPTION 'El catálogo está disponible solo para usuarios de establecimientos habilitados';
  END IF;
  RETURN QUERY
  SELECT l.id, l.principio_activo, l.marca_presentacion, l.laboratorio,
    l.numero_lote, l.fecha_vencimiento,
    GREATEST(l.cantidad_cajas - COALESCE((
      SELECT sum(s.cantidad_solicitada)::INTEGER FROM public.solicitudes_transferencia s
      WHERE s.lote_id = l.id AND s.estado IN ('pendiente_donante', 'pendiente_solicitante', 'aprobada')
    ), 0), 0),
    e.comuna, e.id, e.nombre, l.valor_unitario_clp, l.fuente_valorizacion, l.registro_isp
  FROM public.lotes_medicamentos l
  JOIN public.establecimientos e ON e.id = l.establecimiento_donante_id
  WHERE l.estado = 'disponible'
    AND e.estado = 'habilitado'
    AND l.cantidad_cajas > COALESCE((
      SELECT sum(s.cantidad_solicitada)::INTEGER FROM public.solicitudes_transferencia s
      WHERE s.lote_id = l.id AND s.estado IN ('pendiente_donante', 'pendiente_solicitante', 'aprobada')
    ), 0)
    AND l.fecha_vencimiento >= current_date
    AND l.valor_unitario_clp IS NOT NULL
  ORDER BY l.fecha_vencimiento ASC, l.id DESC;
END;
$$;

CREATE OR REPLACE FUNCTION public.solicitar_transferencia(
  p_lote_id BIGINT, p_establecimiento_solicitante UUID, p_cantidad INTEGER
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_lote public.lotes_medicamentos%ROWTYPE;
  v_reservado INTEGER;
  v_id UUID;
BEGIN
  IF p_cantidad IS NULL OR p_cantidad <= 0 OR NOT public.vlogp_miembro_activo(p_establecimiento_solicitante, NULL) THEN
    RAISE EXCEPTION 'Selecciona un establecimiento habilitado y una cantidad válida';
  END IF;
  SELECT * INTO v_lote FROM public.lotes_medicamentos WHERE id = p_lote_id FOR UPDATE;
  IF NOT FOUND OR v_lote.estado <> 'disponible' OR v_lote.establecimiento_donante_id IS NULL THEN
    RAISE EXCEPTION 'Este lote ya no está disponible para transferencia';
  END IF;
  IF v_lote.establecimiento_donante_id = p_establecimiento_solicitante THEN
    RAISE EXCEPTION 'Un establecimiento no puede solicitar su propio inventario';
  END IF;
  SELECT COALESCE(sum(cantidad_solicitada), 0)::INTEGER INTO v_reservado
  FROM public.solicitudes_transferencia
  WHERE lote_id = p_lote_id AND estado IN ('pendiente_donante', 'pendiente_solicitante', 'aprobada');
  IF p_cantidad > v_lote.cantidad_cajas - v_reservado THEN
    RAISE EXCEPTION 'La cantidad solicitada supera el inventario disponible';
  END IF;
  INSERT INTO public.solicitudes_transferencia (
    lote_id, establecimiento_donante_id, establecimiento_solicitante_id, solicitado_por, cantidad_solicitada
  ) VALUES (
    p_lote_id, v_lote.establecimiento_donante_id, p_establecimiento_solicitante, auth.uid(), p_cantidad
  ) RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

