CREATE OR REPLACE FUNCTION public.vlogp_miembro_activo(p_establecimiento UUID, p_roles TEXT[] DEFAULT NULL)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.establecimiento_usuarios eu
    JOIN public.establecimientos e ON e.id = eu.establecimiento_id
    WHERE eu.establecimiento_id = p_establecimiento
      AND eu.usuario_id = auth.uid()
      AND eu.activo
      AND e.estado = 'habilitado'
      AND (p_roles IS NULL OR eu.rol = ANY (p_roles))
  );
$$;

