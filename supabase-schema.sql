create or replace function public.guard_lote_status_transition()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog, auth
as $$
declare
  request_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
  if new.estado is not distinct from old.estado then
    return new;
  end if;

  if request_email = any (array['diegoarayaa1@gmail.com', 'sgaticam@correo.uss.cl']::text[])
    and old.estado = 'pendiente_revision'
    and new.estado in ('disponible', 'rechazado') then
    return new;
  end if;

  if old.estado = 'disponible'
    and new.estado = 'reservado'
    and old.vendedor_id is distinct from auth.uid()
    and new.reservado_por = request_email then
    return new;
  end if;

  if old.estado = 'reservado'
    and new.estado = 'disponible'
    and new.reservado_por is null
    and (old.reservado_por = request_email or old.vendedor_id = auth.uid()) then
    return new;
  end if;

  if old.estado = 'rechazado'
    and new.estado = 'pendiente_revision'
    and old.vendedor_id = auth.uid()
    and new.motivo_rechazo is null then
    return new;
  end if;

  raise exception 'This medication lot status transition is not allowed'
    using errcode = '42501';
end;
$$;

