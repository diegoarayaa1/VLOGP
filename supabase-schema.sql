    RAISE EXCEPTION 'La eliminación requiere autorización del Director Técnico donante';
  END IF;
  IF EXISTS (SELECT 1 FROM public.solicitudes_transferencia WHERE lote_id = p_lote_id) THEN
    RAISE EXCEPTION 'El lote tiene un historial de transferencias y debe conservarse para trazabilidad';
  END IF;
  DELETE FROM public.lotes_medicamentos
  WHERE id = p_lote_id AND establecimiento_donante_id = p_establecimiento;
  IF NOT FOUND THEN RAISE EXCEPTION 'Lote no encontrado'; END IF;
  RETURN true;
END;
$$;

