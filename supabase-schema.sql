      'referencia_valorizacion', a.referencia_valorizacion, 'creado_en', a.creado_en,
      'contraparte', e.nombre
    ) ORDER BY a.creado_en DESC) FILTER (WHERE a.id IS NOT NULL), '[]'::JSONB)
  FROM public.asientos_compensacion a
  JOIN public.establecimientos e ON e.id = a.contraparte_id
  WHERE a.establecimiento_id = p_establecimiento;
END;
$$;

