CREATE OR REPLACE FUNCTION public.admin_asignar_usuario(
  p_establecimiento UUID, p_email TEXT, p_rol TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_usuario UUID;
BEGIN
  IF NOT public.vlogp_es_admin() THEN
    RAISE EXCEPTION 'No autorizado para asignar usuarios';
  END IF;
  SELECT id INTO v_usuario FROM auth.users WHERE lower(email) = lower(trim(p_email)) LIMIT 1;
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'No existe una cuenta registrada con ese correo';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.establecimientos WHERE id = p_establecimiento) THEN
    RAISE EXCEPTION 'El establecimiento seleccionado no existe';
  END IF;
  INSERT INTO public.establecimiento_usuarios (establecimiento_id, usuario_id, rol, activo, asignado_por)
  VALUES (p_establecimiento, v_usuario, p_rol, true, auth.uid())
  ON CONFLICT (establecimiento_id, usuario_id, rol)
  DO UPDATE SET activo = true, asignado_por = EXCLUDED.asignado_por;
  RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_cambiar_estado_establecimiento(p_id UUID, p_estado TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
