CREATE OR REPLACE FUNCTION public.resolver_transferencia(
  p_id UUID, p_accion TEXT, p_motivo TEXT DEFAULT NULL
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_solicitud public.solicitudes_transferencia%ROWTYPE;
BEGIN
  SELECT * INTO v_solicitud FROM public.solicitudes_transferencia WHERE id = p_id FOR UPDATE;
  IF NOT FOUND OR p_accion NOT IN ('aprobar', 'rechazar') THEN
    RAISE EXCEPTION 'Solicitud o acción inválida';
  END IF;
  IF p_accion = 'rechazar' THEN
    IF NULLIF(trim(p_motivo), '') IS NULL THEN RAISE EXCEPTION 'Debes indicar el motivo del rechazo'; END IF;
    IF v_solicitud.estado = 'pendiente_donante'
      AND public.vlogp_miembro_activo(v_solicitud.establecimiento_donante_id, ARRAY['director_tecnico']) THEN
      UPDATE public.solicitudes_transferencia SET estado = 'rechazada', motivo_resolucion = trim(p_motivo),
        actualizado_en = now() WHERE id = p_id;
      RETURN 'rechazada';
    ELSIF v_solicitud.estado IN ('pendiente_solicitante', 'pendiente_donante')
      AND public.vlogp_miembro_activo(v_solicitud.establecimiento_solicitante_id, ARRAY['director_tecnico']) THEN
      UPDATE public.solicitudes_transferencia SET estado = 'rechazada', motivo_resolucion = trim(p_motivo),
        actualizado_en = now() WHERE id = p_id;
      RETURN 'rechazada';
    END IF;
    RAISE EXCEPTION 'Solo un Director Técnico participante puede rechazar la solicitud';
  END IF;
  IF v_solicitud.estado = 'pendiente_donante'
    AND public.vlogp_miembro_activo(v_solicitud.establecimiento_donante_id, ARRAY['director_tecnico']) THEN
    UPDATE public.solicitudes_transferencia SET estado = 'pendiente_solicitante',
      aprobada_donante_por = auth.uid(), aprobada_donante_en = now(), actualizado_en = now()
    WHERE id = p_id;
    RETURN 'pendiente_solicitante';
  ELSIF v_solicitud.estado = 'pendiente_solicitante'
    AND public.vlogp_miembro_activo(v_solicitud.establecimiento_solicitante_id, ARRAY['director_tecnico']) THEN
    UPDATE public.solicitudes_transferencia SET estado = 'aprobada',
      aprobada_solicitante_por = auth.uid(), aprobada_solicitante_en = now(), actualizado_en = now()
    WHERE id = p_id;
    RETURN 'aprobada';
  END IF;
  RAISE EXCEPTION 'No tienes el rol requerido o la solicitud ya fue resuelta';
END;
$$;

