CREATE OR REPLACE FUNCTION public.confirmar_recepcion_transferencia(p_id UUID, p_cantidad_recibida INTEGER)
RETURNS NUMERIC
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_solicitud public.solicitudes_transferencia%ROWTYPE;
  v_lote public.lotes_medicamentos%ROWTYPE;
  v_monto NUMERIC(16, 2);
BEGIN
  SELECT * INTO v_solicitud FROM public.solicitudes_transferencia WHERE id = p_id FOR UPDATE;
  IF NOT FOUND OR v_solicitud.estado <> 'aprobada'
    OR NOT public.vlogp_miembro_activo(v_solicitud.establecimiento_solicitante_id, ARRAY['director_tecnico']) THEN
    RAISE EXCEPTION 'La recepción requiere una solicitud aprobada y al Director Técnico solicitante';
  END IF;
  IF p_cantidad_recibida IS NULL OR p_cantidad_recibida <= 0 OR p_cantidad_recibida > v_solicitud.cantidad_solicitada THEN
    RAISE EXCEPTION 'La cantidad recibida debe ser positiva y no superar la cantidad aprobada';
  END IF;
  SELECT * INTO v_lote FROM public.lotes_medicamentos WHERE id = v_solicitud.lote_id FOR UPDATE;
  IF NOT FOUND OR v_lote.cantidad_cajas < p_cantidad_recibida OR v_lote.valor_unitario_clp IS NULL
    OR v_lote.fuente_valorizacion IS NULL OR v_lote.referencia_valorizacion IS NULL THEN
    RAISE EXCEPTION 'El lote no tiene stock o respaldo de valorización suficiente';
  END IF;
  v_monto := round(v_lote.valor_unitario_clp * p_cantidad_recibida, 2);
  UPDATE public.lotes_medicamentos
    SET cantidad_cajas = cantidad_cajas - p_cantidad_recibida
    WHERE id = v_lote.id;
  UPDATE public.solicitudes_transferencia SET estado = 'recibida',
    cantidad_recibida = p_cantidad_recibida, confirmada_por = auth.uid(),
    confirmada_en = now(), actualizado_en = now() WHERE id = p_id;
  INSERT INTO public.asientos_compensacion (
    transferencia_id, establecimiento_id, contraparte_id, tipo, cantidad,
    valor_unitario_clp, monto_clp, fuente_valorizacion, referencia_valorizacion, creado_por
  ) VALUES
    (p_id, v_solicitud.establecimiento_donante_id, v_solicitud.establecimiento_solicitante_id,
     'credito', p_cantidad_recibida, v_lote.valor_unitario_clp, v_monto,
     v_lote.fuente_valorizacion, v_lote.referencia_valorizacion, auth.uid()),
    (p_id, v_solicitud.establecimiento_solicitante_id, v_solicitud.establecimiento_donante_id,
     'debito', p_cantidad_recibida, v_lote.valor_unitario_clp, v_monto,
     v_lote.fuente_valorizacion, v_lote.referencia_valorizacion, auth.uid());
  RETURN v_monto;
END;
$$;

CREATE OR REPLACE FUNCTION public.mi_cuenta_compensacion(p_establecimiento UUID)
RETURNS TABLE (saldo_clp NUMERIC, asientos JSONB)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
BEGIN
  IF NOT public.vlogp_miembro_activo(p_establecimiento, NULL) THEN
    RAISE EXCEPTION 'No tienes acceso a esta cuenta de compensación';
  END IF;
  RETURN QUERY
  SELECT COALESCE(sum(CASE WHEN a.tipo = 'credito' THEN a.monto_clp ELSE -a.monto_clp END), 0)::NUMERIC,
    COALESCE(jsonb_agg(jsonb_build_object(
      'id', a.id, 'transferencia_id', a.transferencia_id, 'tipo', a.tipo,
      'cantidad', a.cantidad, 'valor_unitario_clp', a.valor_unitario_clp,
