create function public.admin_moderate_lote(p_lot_id bigint, p_action text, p_rejection_reason text default null)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  request_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  next_state text;
  updated_count integer;
begin
  if request_email <> all (array['diegoarayaa1@gmail.com', 'sgaticam@correo.uss.cl']::text[]) then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  if p_action = 'approve' then
    next_state := 'disponible';
  elsif p_action = 'reject' then
    if nullif(btrim(p_rejection_reason), '') is null then
      raise exception 'A rejection reason is required' using errcode = '22023';
    end if;
    next_state := 'rechazado';
  else
    raise exception 'Invalid moderation action' using errcode = '22023';
  end if;

  update public.lotes_medicamentos
  set estado = next_state,
      motivo_rechazo = case when next_state = 'rechazado' then btrim(p_rejection_reason) else null end
  where id = p_lot_id
    and estado = 'pendiente_revision';
  get diagnostics updated_count = row_count;
  return updated_count = 1;
end;
$$;

